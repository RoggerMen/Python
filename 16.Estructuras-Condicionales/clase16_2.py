x = 15
y = 20

# USAMOS LA PALABRA "RESERVADA" 'and' SE DEBEN CUMPLIR AMBAS CONDICIONES SI O SI PARA EJECUTAR
if x > 10 and y > 25:
    print(f"X -> {x} es mayor que 10 y Y -> {y} es mayor que 15")

# USAMOS LA PALABRA RESERVADA "or" SE PUEDE CUMPLIR UNA DE LAS 2 CONDICIONES O AMBAS PARA QUE EJECUTE
if x > 10 or y > 25:
    print(f"X -> {x} es mayor que 10 O Y -> {y} es mayor que 25")


# USAMOS LA PALABRA RESERVADA "not" PARA NEGAR UNA CONDICIONAL QUE QUERRAMOS EVALUAR
if not x > 10:
    print(f"X -> {x} NO es mayor que 10")

